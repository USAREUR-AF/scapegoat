# shellcheck shell=bash disable=SC2034,SC2154  # globals come from install-field-node.sh
# Component "usb_eth" (on with USB_ETH=on, also under COMPONENTS="none"): a hot-plug USB Ethernet adapter as an optional uplink.
# One netplan file, /etc/netplan/56-usb-ethernet.yaml, matching any interface named enx*:
# optional (boot never waits for it), DHCPv4 with a route metric, no DHCPv6, IPv4 link-local.
#   USB_ETH_ROUTE_METRIC  the metric of its default route. Lower wins: below the Wi-Fi's (for
#                         example 300 under a Wi-Fi at 600) makes a plugged cable the uplink;
#                         above it (for example 700) means it never takes the uplink.
# The file is written, checked with `netplan generate`, and NOT applied: netplan apply would
# touch every link, including the one you are connected over. It takes effect on the next
# plug-in, reboot or deliberate `sudo netplan apply`. Another usb-ethernet netplan file (a
# hand-made one under another name) is replaced by this one.
# Adapters that an earlier systemd-networkd file claims by name keep that owner: first-bite's
# pi-tap bridge ports (05-pi-tap-<iface>.network) sort before netplan's 10-netplan-* files, so on
# a tap node only a further adapter plugged in takes this DHCP uplink.
# Sourced by install-field-node.sh.

usb_eth_phases=1
USB_ETH_FILE="$ROOT/etc/netplan/56-usb-ethernet.yaml"

usb_eth_render() {
  cat <<EOT
# Generated by install-field-node.sh (component usb_eth) from /etc/field-node/site.env.
# A hot-plug USB Ethernet adapter (enx*) as an optional uplink, route metric ${USB_ETH_ROUTE_METRIC}.
network:
  version: 2
  ethernets:
    usb-ethernet:
      match:
        name: "enx*"
      optional: true
      dhcp4: true
      dhcp4-overrides:
        route-metric: ${USB_ETH_ROUTE_METRIC}
      dhcp6: false
      link-local: [ipv4]
EOT
}

usb_eth_others() {  # other netplan files that configure the USB adapter (hand-made)
  local f
  for f in "$ROOT"/etc/netplan/*usb-ethernet*.yaml; do
    [[ -f "$f" && "$f" != "$USB_ETH_FILE" ]] && echo "$f"
  done
  return 0
}

usb_eth_preflight() {
  if ! [[ "${USB_ETH_ROUTE_METRIC:-}" =~ ^[0-9]+$ ]] || (( USB_ETH_ROUTE_METRIC < 1 || USB_ETH_ROUTE_METRIC > 65535 )); then
    die "USB_ETH_ROUTE_METRIC must be 1-65535 (lower than the Wi-Fi's to be the preferred uplink)"
  fi
}

usb_eth_write() {
  mkdir -p "$(dirname "$USB_ETH_FILE")"
  usb_eth_render > "$USB_ETH_FILE.tmp"
  chmod 600 "$USB_ETH_FILE.tmp"
  mv "$USB_ETH_FILE.tmp" "$USB_ETH_FILE"
}

usb_eth_apply() {
  phase "USB Ethernet uplink (enx*, route metric ${USB_ETH_ROUTE_METRIC})"
  local tmp f changed=0
  tmp=$(mktemp); usb_eth_render > "$tmp"
  if same_file "$tmp" "$USB_ETH_FILE"; then ok "$USB_ETH_FILE current"
  else act "write $USB_ETH_FILE" usb_eth_write; changed=1; fi
  rm -f "$tmp"
  local claimed="" n
  for n in "$ROOT"/etc/systemd/network/0[0-9]-*enx*.network; do [[ -f "$n" ]] && claimed+="${n##*/} "; done
  [[ -z "$claimed" ]] || note "adapters claimed by earlier networkd files keep their owner: $claimed"
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    act "remove $f (replaced by $USB_ETH_FILE)" rm -f "$f"; changed=1
  done < <(usb_eth_others)
  if [[ $changed -eq 1 && $CHECK -eq 0 ]]; then
    if [[ -z "$ROOT" ]] && command -v netplan >/dev/null; then
      netplan generate || die "netplan generate refused the configuration (above)"
    fi
    note "takes effect on the next plug-in, reboot or 'sudo netplan apply' (not applied now)"
  fi
}

usb_eth_verify() {
  if [[ -f "$USB_ETH_FILE" ]]; then ok "$USB_ETH_FILE present"
  else echo "    MISSING: $USB_ETH_FILE" >&2; FAILED=1; fi
}

usb_eth_uninstall() {
  phase "USB Ethernet uplink"
  if [[ -f "$USB_ETH_FILE" ]]; then act "remove $USB_ETH_FILE" rm -f "$USB_ETH_FILE"; fi
  note "not applied: the adapter keeps its current address until the next plug-in, reboot or netplan apply"
}
