# shellcheck shell=bash disable=SC2034,SC2154  # globals come from install-field-node.sh
# Component "passthrough": publish a sensor's datagrams unchanged to the Billie island, for a
# format no kid ingests yet. One systemd instance per entry:
#   PASSTHROUGH="<name> ..."  and per name, with KEY = the name in capitals, "-" as "_":
#   PASSTHROUGH_<KEY>_BIND, PASSTHROUGH_<KEY>_PORT   where the sensor sends (UDP)
#   PASSTHROUGH_<KEY>_SOURCE_CIDR                     who may send (others are dropped)
#   PASSTHROUGH_<KEY>_KEY                             island key; {host} becomes NODE_NAME
#   PASSTHROUGH_<KEY>_CONTENT_TYPE                    default application/octet-stream
# When ufw is active, an input rule for each instance is added (and removed on uninstall).
# Sourced by install-field-node.sh.

passthrough_phases=1
pt_var() { local v; v="PASSTHROUGH_$(var_key "$1")_$2"; echo "${!v:-$3}"; }
pt_ufw_active() { command -v ufw >/dev/null && ufw status 2>/dev/null | grep -q "^Status: active"; }
pt_rule() { echo "in on $SENSOR_IFACE from $(pt_var "$1" SOURCE_CIDR) to $(pt_var "$1" BIND) port $(pt_var "$1" PORT) proto udp"; }

passthrough_preflight() {
  [[ -n "${PASSTHROUGH:-}" ]] || return 0
  python3 - <<'PY' || die "fix the passthrough values above"
import ipaddress, os, re, sys
e, bad = os.environ, []
for name in e.get("PASSTHROUGH", "").split():
    key = "PASSTHROUGH_" + name.upper().replace("-", "_") + "_"
    g = lambda f, d="": e.get(key + f, d).strip()
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,40}", name): bad.append(f"passthrough name {name!r}: lowercase letters, digits, -")
    try: ipaddress.IPv4Address(g("BIND"))
    except ValueError: bad.append(f"{key}BIND must be an IPv4 address of this node")
    if not (g("PORT").isdigit() and 1 <= int(g("PORT")) <= 65535): bad.append(f"{key}PORT must be 1-65535")
    try: ipaddress.ip_network(g("SOURCE_CIDR"), strict=False)
    except ValueError: bad.append(f"{key}SOURCE_CIDR must be a network, e.g. 192.0.2.10/32")
    if not re.fullmatch(r"[A-Za-z0-9_.{}/-]+", g("KEY")): bad.append(f"{key}KEY must be an island key like radar/asterix/{{host}}")
for b in bad: print("    -", b)
sys.exit(1 if bad else 0)
PY
}

passthrough_render() {  # <name> -> settings file content
  cat <<EOT
# Generated by install-field-node.sh from /etc/field-node/site.env (passthrough $1).
PT_BIND=$(pt_var "$1" BIND)
PT_PORT=$(pt_var "$1" PORT)
PT_SOURCE_CIDR=$(pt_var "$1" SOURCE_CIDR)
PT_KEY=$(pt_var "$1" KEY | sed "s|{host}|${NODE_NAME}|g")
PT_ISLAND_REST=${ISLAND_REST:-http://127.0.0.1:8000}
PT_CONTENT_TYPE=$(pt_var "$1" CONTENT_TYPE application/octet-stream)
EOT
}

passthrough_apply() {
  phase "Pass-through publish (${PASSTHROUGH:-none})"
  [[ -n "${PASSTHROUGH:-}" ]] || { note "no pass-through in the site file"; return 0; }
  local before=$DRIFT changed=0 n tmp unit env_changed
  DRIFT=0
  install_file "$HERE/bin/field-node-passthrough" "$LIBEXEC_DIR/field-node-passthrough" 755 && changed=1
  install_file "$HERE/units/field-node-passthrough@.service" "$UNIT_DIR/field-node-passthrough@.service" 644 && changed=1
  if [[ $changed -eq 1 ]]; then act "systemctl daemon-reload" systemctl daemon-reload; fi
  for n in $PASSTHROUGH; do
    unit="field-node-passthrough@$n.service"
    tmp=$(mktemp); passthrough_render "$n" > "$tmp"
    env_changed=0
    install_file "$tmp" "$ETC/passthrough-$n.env" 644 && env_changed=1
    rm -f "$tmp"
    if ! systemctl is-active --quiet "$unit" 2>/dev/null; then
      act "enable and start $unit" systemctl enable --now "$unit"
    elif [[ $env_changed -eq 1 || $changed -eq 1 ]]; then
      act "restart $unit (settings or program changed)" systemctl restart "$unit"
    fi
    if pt_ufw_active && ! ufw status | grep -q "field-node-passthrough-$n"; then
      # shellcheck disable=SC2046
      act "ufw allow $(pt_rule "$n")" ufw allow $(pt_rule "$n") comment "field-node-passthrough-$n"
    fi
  done
  [[ $DRIFT -eq 1 ]] || ok "pass-through current and running"
  [[ $before -eq 0 ]] || DRIFT=1
}

passthrough_verify() { local n; for n in ${PASSTHROUGH:-}; do expect_active "field-node-passthrough@$n.service"; done; }

passthrough_uninstall() {
  phase "Pass-through publish"
  local n
  for n in ${PASSTHROUGH:-}; do
    if [[ -f "$ETC/passthrough-$n.env" ]]; then
      act "stop field-node-passthrough@$n" bash -c "systemctl disable --now 'field-node-passthrough@$n.service' >/dev/null 2>&1 || true; rm -f '$ETC/passthrough-$n.env'"
    fi
    if pt_ufw_active && ufw status | grep -q "field-node-passthrough-$n"; then
      # shellcheck disable=SC2046
      act "ufw delete allow $(pt_rule "$n")" ufw delete allow $(pt_rule "$n")
    fi
  done
  if [[ -f "$UNIT_DIR/field-node-passthrough@.service" ]]; then act "remove the passthrough unit" rm -f "$UNIT_DIR/field-node-passthrough@.service"; fi
  if [[ -f "$LIBEXEC_DIR/field-node-passthrough" ]]; then act "remove $LIBEXEC_DIR/field-node-passthrough" rm -f "$LIBEXEC_DIR/field-node-passthrough"; fi
}
